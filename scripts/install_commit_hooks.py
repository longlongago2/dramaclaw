"""Install pre-commit with safe inventory maintenance before its stash step."""

from __future__ import annotations

from pathlib import Path
import shutil
import subprocess


MARKER = "# DramaClaw inventory preparation (before pre-commit stashing)"
PREPARE = '''# DramaClaw inventory preparation (before pre-commit stashing)
if [ -f scripts/install_commit_hooks.py ] && [ -f scripts/compliance/update_license_inventory.py ]; then
    if [ ! -x "$INSTALL_PYTHON" ]; then
        echo 'Hook Python is unavailable; rerun python scripts/install_commit_hooks.py.' >&2
        exit 1
    fi
    "$INSTALL_PYTHON" -X utf8 -m scripts.compliance.update_license_inventory --stage || exit $?
fi

'''


def install_hooks(root: Path) -> None:
    executable = shutil.which("pre-commit")
    if executable is None:
        raise RuntimeError("Install pre-commit first: uv tool install pre-commit")
    subprocess.run([executable, "install", "--install-hooks"], cwd=root, check=True)
    location = subprocess.check_output(
        ["git", "rev-parse", "--git-path", "hooks/pre-commit"], cwd=root, text=True,
    ).strip()
    hook = root / location
    source = hook.read_text(encoding="utf-8")
    if MARKER in source:
        return
    anchor = 'HERE="$(cd "$(dirname "$0")" && pwd)"'
    if "# File generated by pre-commit:" not in source or anchor not in source:
        raise RuntimeError("Unrecognized pre-commit hook; preserved without modification.")
    hook.write_text(source.replace(anchor, PREPARE + anchor, 1), encoding="utf-8", newline="\n")
    print("Installed commit checks with safe automatic license inventory maintenance.")


if __name__ == "__main__":
    repository = Path(subprocess.check_output(
        ["git", "rev-parse", "--show-toplevel"], text=True,
    ).strip())
    install_hooks(repository)
